CREATE TABLE agent_chat_sessions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  interview_session_id VARCHAR(36) NOT NULL,
  goal VARCHAR(32),
  provider_id VARCHAR(64),
  created_at TIMESTAMP(6) NOT NULL,
  updated_at TIMESTAMP(6) NOT NULL,
  CONSTRAINT uk_agent_chat_interview_session UNIQUE (interview_session_id)
);

CREATE TABLE agent_chat_messages (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  session_id BIGINT NOT NULL,
  role VARCHAR(16) NOT NULL,
  content TEXT NOT NULL,
  sequence_num INTEGER NOT NULL,
  completed BOOLEAN NOT NULL DEFAULT TRUE,
  error_message VARCHAR(500),
  created_at TIMESTAMP(6) NOT NULL,
  updated_at TIMESTAMP(6) NOT NULL,
  CONSTRAINT uk_agent_message_session_sequence UNIQUE (session_id, sequence_num),
  CONSTRAINT fk_agent_message_session FOREIGN KEY (session_id) REFERENCES agent_chat_sessions(id),
  CONSTRAINT agent_chat_messages_role_check CHECK (role IN ('USER', 'ASSISTANT'))
);

CREATE INDEX idx_agent_chat_messages_session_sequence
  ON agent_chat_messages (session_id, sequence_num);
