CREATE TABLE resume_edit_drafts (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  resume_id BIGINT NOT NULL,
  version INTEGER NOT NULL DEFAULT 1,
  source VARCHAR(20) NOT NULL,
  name VARCHAR(200),
  email VARCHAR(200),
  phone VARCHAR(80),
  location VARCHAR(200),
  target_position VARCHAR(200),
  skills TEXT,
  work_experience TEXT,
  projects TEXT,
  education TEXT,
  self_evaluation TEXT,
  raw_text TEXT,
  created_at TIMESTAMP(6) NOT NULL,
  updated_at TIMESTAMP(6) NOT NULL,
  CONSTRAINT uk_resume_edit_draft_resume UNIQUE (resume_id),
  CONSTRAINT fk_resume_edit_draft_resume FOREIGN KEY (resume_id) REFERENCES resumes(id) ON DELETE CASCADE,
  CONSTRAINT resume_edit_draft_source_check CHECK (source IN ('ORIGINAL', 'AI_DRAFT', 'MANUAL', 'APPLIED'))
);

CREATE INDEX idx_resume_edit_draft_updated_at ON resume_edit_drafts (updated_at);

ALTER TABLE resumes ADD COLUMN original_resume_text TEXT;
UPDATE resumes SET original_resume_text = resume_text WHERE original_resume_text IS NULL;
