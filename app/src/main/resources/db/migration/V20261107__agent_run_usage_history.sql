CREATE TABLE agent_run_usages (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  owner_key VARCHAR(64),
  interview_session_id VARCHAR(36) NOT NULL,
  agent_session_id VARCHAR(36) NOT NULL,
  run_id VARCHAR(36) NOT NULL,
  run_status VARCHAR(16) NOT NULL,
  run_started_at TIMESTAMP(6),
  run_finished_at TIMESTAMP(6),
  prompt_tokens INTEGER NOT NULL DEFAULT 0,
  completion_tokens INTEGER NOT NULL DEFAULT 0,
  total_tokens INTEGER NOT NULL DEFAULT 0,
  model_calls INTEGER NOT NULL DEFAULT 0,
  duration_millis BIGINT NOT NULL DEFAULT 0,
  cost NUMERIC(20, 10),
  currency VARCHAR(8),
  provider VARCHAR(64),
  model VARCHAR(128),
  created_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT uk_agent_run_usage_run_id UNIQUE (run_id),
  CONSTRAINT agent_run_usages_status_check
    CHECK (run_status IN ('COMPLETED', 'FAILED', 'CANCELLED'))
);

CREATE INDEX idx_agent_run_usage_owner_created
  ON agent_run_usages (owner_key, created_at DESC);

CREATE INDEX idx_agent_run_usage_owner_provider_currency
  ON agent_run_usages (owner_key, provider, currency);

COMMENT ON TABLE agent_run_usages IS '按 Agent 运行保存的 Token、耗时和费用快照';

-- 迁移已有会话表中仍可识别的最近一次运行；后续每次运行由 Agent 终态自动写入。
INSERT INTO agent_run_usages (
  owner_key, interview_session_id, agent_session_id, run_id, run_status,
  run_started_at, run_finished_at, prompt_tokens, completion_tokens, total_tokens,
  model_calls, duration_millis, cost, currency, provider, model, created_at
)
SELECT
  owner_key, interview_session_id, agent_session_id, run_id,
  COALESCE(run_status, 'COMPLETED'), run_started_at, run_finished_at,
  COALESCE(run_prompt_tokens, 0), COALESCE(run_completion_tokens, 0),
  COALESCE(run_total_tokens, 0), COALESCE(run_model_calls, 0),
  COALESCE(run_duration_millis, 0), run_cost, run_currency, run_provider, run_model,
  COALESCE(run_finished_at, run_started_at, updated_at, created_at, CURRENT_TIMESTAMP)
FROM agent_chat_sessions
WHERE run_id IS NOT NULL
  AND run_status IN ('COMPLETED', 'FAILED', 'CANCELLED')
  AND (
    run_prompt_tokens IS NOT NULL OR run_completion_tokens IS NOT NULL
    OR run_total_tokens IS NOT NULL OR run_model_calls IS NOT NULL
    OR run_duration_millis IS NOT NULL OR run_cost IS NOT NULL
  )
ON CONFLICT (run_id) DO NOTHING;
